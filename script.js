const priceFormatter = new Intl.NumberFormat("en-IN", {
  style: "currency",
  currency: "INR",
  maximumFractionDigits: 0
});

const chevronLeftIcon = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="m15 18-6-6 6-6"/></svg>';
const chevronRightIcon = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="m9 18 6-6-6-6"/></svg>';
const externalLinkIcon = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M7 17 17 7M9 7h8v8"/></svg>';

let activeCategory = "All";

function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "\"": "&quot;",
    "'": "&#039;"
  })[character]);
}

function toNumber(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number : 0;
}

function formatPrice(value) {
  return priceFormatter.format(toNumber(value));
}

function normalizeImages(images) {
  return Array.isArray(images) ? images.filter(Boolean) : [];
}

function getDiscount(product) {
  if (product.discount) {
    return String(product.discount).trim();
  }

  const original = toNumber(product.originalPrice);
  const discounted = toNumber(product.discountPrice);

  if (original > 0 && discounted >= 0) {
    return `${Math.round((1 - discounted / original) * 100)}%`;
  }

  return "";
}

function discountToNumber(discount) {
  const match = String(discount).match(/\d+/);
  return match ? Number(match[0]) : 0;
}

function createProductCard(product) {
  const safeName = escapeHTML(product.name);
  const images = normalizeImages(product.images);
  const discount = getDiscount(product);
  const hasSlider = images.length > 1;

  const slides = images.map((image, imageIndex) => `
    <div class="slider-slide">
      <img src="${escapeHTML(image)}" alt="${safeName} — view ${imageIndex + 1}" loading="lazy" decoding="async" draggable="false">
    </div>
  `).join("");

  const counter = hasSlider ? `
    <span class="slider-counter" data-counter aria-hidden="true">01 / ${String(images.length).padStart(2, "0")}</span>
  ` : "";

  const arrows = hasSlider ? `
    <button class="slider-arrow slider-arrow-prev" type="button" data-prev aria-label="Previous image for ${safeName}">${chevronLeftIcon}</button>
    <button class="slider-arrow slider-arrow-next" type="button" data-next aria-label="Next image for ${safeName}">${chevronRightIcon}</button>
  ` : "";

  const dots = hasSlider ? `
    <div class="slider-dots" role="group" aria-label="Choose image for ${safeName}">
      ${images.map((_, dotIndex) => `
        <button class="slider-dot${dotIndex === 0 ? " is-active" : ""}" type="button" data-dot data-index="${dotIndex}" aria-label="Show image ${dotIndex + 1} of ${images.length} for ${safeName}" aria-current="${dotIndex === 0}"></button>
      `).join("")}
    </div>
  ` : "";

  return `
    <article class="product-card" data-product-id="${escapeHTML(product.id)}">
      <div class="card-media">
        ${discount ? `<span class="discount-badge">SAVE ${escapeHTML(discount)}</span>` : ""}
        <div class="slider" data-slider>
          <div class="slider-viewport" data-viewport role="region" aria-label="${safeName} image gallery" tabindex="0">
            <div class="slider-track" data-track>${slides}</div>
            ${counter}
            ${arrows}
          </div>
          ${dots}
        </div>
      </div>
      <div class="card-body">
        <span class="product-category">${escapeHTML(product.category || "Uncategorized")}</span>
        <h3 class="product-name">${safeName}</h3>
        <p class="product-description">${escapeHTML(product.description)}</p>
        <div class="price-row">
          <span class="price-current">${formatPrice(product.discountPrice)}</span>
          <span class="price-original">${formatPrice(product.originalPrice)}</span>
          ${discount ? `<span class="price-note">You save ${escapeHTML(discount)}</span>` : ""}
        </div>
        <a class="buy-button" href="${escapeHTML(product.affiliateLink || "#")}" target="_blank" rel="sponsored nofollow noopener noreferrer" aria-label="Buy ${safeName} — opens in a new tab">
          Buy Now
          ${externalLinkIcon}
        </a>
      </div>
    </article>
  `;
}

function initSlider(slider) {
  const viewport = slider.querySelector("[data-viewport]");
  const track = slider.querySelector("[data-track]");
  const previousButton = slider.querySelector("[data-prev]");
  const nextButton = slider.querySelector("[data-next]");
  const counter = slider.querySelector("[data-counter]");
  const dots = Array.from(slider.querySelectorAll("[data-dot]"));
  const slideCount = slider.querySelectorAll(".slider-slide").length;

  if (!viewport || !track || slideCount < 2) {
    return;
  }

  let currentIndex = 0;
  let startX = 0;
  let startY = 0;
  let pointerId = null;
  let isDragging = false;
  let isHorizontal = false;

  function goTo(index) {
    const clampedIndex = Math.max(0, Math.min(slideCount - 1, index));
    if (clampedIndex === currentIndex) {
      return;
    }

    currentIndex = clampedIndex;
    updateSlider();
  }

  function updateSlider() {
    track.style.transform = `translate3d(${-currentIndex * 100}%, 0, 0)`;
    previousButton.disabled = currentIndex === 0;
    nextButton.disabled = currentIndex === slideCount - 1;

    dots.forEach((dot, dotIndex) => {
      const isActive = dotIndex === currentIndex;
      dot.classList.toggle("is-active", isActive);
      dot.setAttribute("aria-current", String(isActive));
    });

    if (counter) {
      counter.textContent = `${String(currentIndex + 1).padStart(2, "0")} / ${String(slideCount).padStart(2, "0")}`;
    }
  }

  function finishDrag(event, allowSwipe = true) {
    if (!isDragging || event.pointerId !== pointerId) {
      return;
    }

    const deltaX = event.clientX - startX;
    isDragging = false;
    track.classList.remove("is-dragging");
    viewport.classList.remove("is-dragging");

    if (viewport.hasPointerCapture && viewport.hasPointerCapture(pointerId)) {
      viewport.releasePointerCapture(pointerId);
    }

    if (allowSwipe && isHorizontal && Math.abs(deltaX) > 45) {
      goTo(currentIndex + (deltaX < 0 ? 1 : -1));
    } else {
      track.style.transform = `translate3d(${-currentIndex * 100}%, 0, 0)`;
    }

    pointerId = null;
    isHorizontal = false;
  }

  previousButton.addEventListener("click", () => goTo(currentIndex - 1));
  nextButton.addEventListener("click", () => goTo(currentIndex + 1));

  dots.forEach((dot, dotIndex) => {
    dot.addEventListener("click", () => goTo(dotIndex));
  });

  viewport.addEventListener("keydown", (event) => {
    if (event.key === "ArrowRight") {
      event.preventDefault();
      goTo(currentIndex + 1);
    }

    if (event.key === "ArrowLeft") {
      event.preventDefault();
      goTo(currentIndex - 1);
    }

    if (event.key === "Home") {
      event.preventDefault();
      goTo(0);
    }

    if (event.key === "End") {
      event.preventDefault();
      goTo(slideCount - 1);
    }
  });

  viewport.addEventListener("pointerdown", (event) => {
    if (event.pointerType === "mouse" && event.button !== 0) {
      return;
    }

    if (event.target.closest("button")) {
      return;
    }

    isDragging = true;
    isHorizontal = false;
    startX = event.clientX;
    startY = event.clientY;
    pointerId = event.pointerId;
    track.classList.add("is-dragging");
    viewport.classList.add("is-dragging");
  });

  viewport.addEventListener("pointermove", (event) => {
    if (!isDragging || event.pointerId !== pointerId) {
      return;
    }

    const deltaX = event.clientX - startX;
    const deltaY = event.clientY - startY;

    if (!isHorizontal) {
      if (Math.abs(deltaX) < 8 && Math.abs(deltaY) < 8) {
        return;
      }

      isHorizontal = Math.abs(deltaX) > Math.abs(deltaY);

      if (!isHorizontal) {
        finishDrag(event, false);
        return;
      }

      if (viewport.setPointerCapture) {
        viewport.setPointerCapture(pointerId);
      }
    }

    event.preventDefault();
    const limitedDelta = Math.max(-viewport.clientWidth, Math.min(viewport.clientWidth, deltaX));
    track.style.transform = `translate3d(${-currentIndex * 100}%, 0, 0) translateX(${limitedDelta}px)`;
  });

  viewport.addEventListener("pointerup", (event) => finishDrag(event));
  viewport.addEventListener("pointercancel", (event) => finishDrag(event, false));
  viewport.addEventListener("pointerleave", (event) => {
    if (event.pointerType === "mouse" && isDragging) {
      finishDrag(event);
    }
  });

  updateSlider();
}

function renderCategories() {
  const categories = ["All", ...new Set(products.map((product) => product.category || "Uncategorized"))];

  elements.categoryFilters.innerHTML = categories.map((category) => {
    const isActive = category === activeCategory;
    const label = category === "All" ? "All Products" : category;

    return `
      <button class="filter-button${isActive ? " is-active" : ""}" type="button" data-category="${escapeHTML(category)}" aria-pressed="${isActive}">
        ${escapeHTML(label)}
      </button>
    `;
  }).join("");
}

function renderProducts() {
  const query = elements.searchInput.value.trim().toLowerCase();

  const visibleProducts = products.filter((product) => {
    const matchesCategory = activeCategory === "All" || (product.category || "Uncategorized") === activeCategory;
    const matchesSearch = String(product.name || "").toLowerCase().includes(query);
    return matchesCategory && matchesSearch;
  });

  elements.resultCount.textContent = visibleProducts.length;
  elements.productsGrid.innerHTML = visibleProducts.map(createProductCard).join("");
  elements.emptyState.hidden = visibleProducts.length > 0;

  elements.productsGrid.querySelectorAll("[data-slider]").forEach(initSlider);
}

function renderStats() {
  const totalImages = products.reduce((total, product) => total + normalizeImages(product.images).length, 0);
  const highestDiscount = products.reduce((highest, product) => Math.max(highest, discountToNumber(getDiscount(product))), 0);

  elements.dealCount.textContent = products.length;
  elements.imageCount.textContent = totalImages;
  elements.maxDiscount.textContent = highestDiscount > 0 ? `${highestDiscount}%` : "—";
}

function setActiveCategory(category) {
  activeCategory = category;

  elements.categoryFilters.querySelectorAll(".filter-button").forEach((button) => {
    const isActive = button.dataset.category === category;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  renderProducts();
}

function closeMenu() {
  elements.menuToggle.setAttribute("aria-expanded", "false");
  elements.menuToggle.setAttribute("aria-label", "Open menu");
  elements.primaryNav.classList.remove("is-open");
}

elements.searchInput.addEventListener("input", renderProducts);

elements.categoryFilters.addEventListener("click", (event) => {
  const button = event.target.closest(".filter-button");
  if (button) {
    setActiveCategory(button.dataset.category);
  }
});

elements.resetFilters.addEventListener("click", () => {
  elements.searchInput.value = "";
  setActiveCategory("All");
  elements.searchInput.focus();
});

elements.menuToggle.addEventListener("click", () => {
  const isOpen = elements.menuToggle.getAttribute("aria-expanded") === "true";
  elements.menuToggle.setAttribute("aria-expanded", String(!isOpen));
  elements.menuToggle.setAttribute("aria-label", isOpen ? "Open menu" : "Close menu");
  elements.primaryNav.classList.toggle("is-open", !isOpen);
});

elements.primaryNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

document.addEventListener("click", (event) => {
  if (!event.target.closest(".site-header")) {
    closeMenu();
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeMenu();
  }
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 860) {
    closeMenu();
  }
});

renderStats();
renderCategories();
renderProducts();
